export interface CareerLevelPosition {
  /** Authored board seed, or the generated level's position-derived ID. */
  id: string
  /** Present when this position belongs to an infinite Career section. */
  infiniteRepeat?: ResolvedCareerLevel['infiniteRepeat']
  level: ResolvedCareerLevelConfiguration
  x: number
  y: number
}

interface ExpandedCareerLevel {
  isInfiniteRepeat: boolean
  isInfiniteTail: boolean
  repeatIndex: number
  sourceIndex: number
  source: CareerLevel
}

interface ResolvedCareerLevelEntry extends ExpandedCareerLevel {
  level: ResolvedCareerLevelConfiguration
}

export const EMPTY_CAREER_LEVEL_GENERATION: CareerLevelGeneration = { infiniteRepeats: {} }

function isCareerLevelBuilder(data: CareerLevel['data']): data is CareerLevelBuilder {
  return typeof data === 'function'
}

function isCareerLevelDefinitionList(data: CareerLevelData): data is readonly ClassicGameDefinition[] {
  return Array.isArray(data)
}

function getFiniteRepeatCount(level: CareerLevel): number {
  const repeat = level.repeat ?? 0
  if (repeat === 'infinite') return 0
  if (!Number.isSafeInteger(repeat) || repeat < 0) {
    throw new Error('Career level repeat must be a non-negative integer.')
  }
  return repeat
}

function getInfiniteRepeatCount(generation: CareerLevelGeneration, sourceIndex: number): number {
  const count = generation.infiniteRepeats[String(sourceIndex)] ?? 1
  return Number.isSafeInteger(count) && count > 0 ? count : 1
}

/** Expands available Career entries, stopping after the active infinite-repeat section. */
function expandCareerLevels(levels: readonly CareerLevel[], generation: CareerLevelGeneration): ExpandedCareerLevel[] {
  const expandedLevels: ExpandedCareerLevel[] = []
  for (const [sourceIndex, source] of levels.entries()) {
    const isInfiniteRepeat = source.repeat === 'infinite'
    const levelCount = isInfiniteRepeat
      ? getInfiniteRepeatCount(generation, sourceIndex)
      : getFiniteRepeatCount(source) + 1
    for (let repeatIndex = 0; repeatIndex < levelCount; repeatIndex += 1) {
      expandedLevels.push({
        isInfiniteRepeat,
        isInfiniteTail: isInfiniteRepeat && repeatIndex === levelCount - 1,
        repeatIndex,
        source,
        sourceIndex,
      })
    }
    // A later control will mark this section complete and allow the source list to continue.
    if (isInfiniteRepeat) break
  }
  return expandedLevels
}

function resolveCareerLevelEntries(levels: readonly CareerLevel[], generation: CareerLevelGeneration): ResolvedCareerLevelEntry[] {
  let previousLevel: ResolvedCareerLevelConfiguration | undefined
  return expandCareerLevels(levels, generation).map((entry, index) => {
    const { source } = entry
    const { data, repeat: _repeat, ...staticFields } = source
    const overrides = isCareerLevelBuilder(data) ? data(index + 1, previousLevel) : undefined
    const level = {
      ...staticFields,
      ...overrides,
      ...(isCareerLevelBuilder(data) ? {} : { data }),
    } satisfies ResolvedCareerLevelConfiguration
    previousLevel = level
    return { ...entry, level }
  })
}

/** Resolves builders in expanded level order so each receives the prior complete configuration. */
export function resolveCareerLevelConfigurations(levels: readonly CareerLevel[] = careerLevels, generation: CareerLevelGeneration = EMPTY_CAREER_LEVEL_GENERATION): ResolvedCareerLevelConfiguration[] {
  return resolveCareerLevelEntries(levels, generation).map(({ level }) => level)
}

/** Resolves relative authored offsets into absolute map coordinates. */
export function resolveCareerLevelPositions(levels: readonly CareerLevel[] = careerLevels, generation: CareerLevelGeneration = EMPTY_CAREER_LEVEL_GENERATION): CareerLevelPosition[] {
  let previous = { x: 0, y: 0 }
  return resolveCareerLevelEntries(levels, generation).map(({ isInfiniteRepeat, isInfiniteTail, level, repeatIndex, source, sourceIndex }, index) => {
    const position = level.origin === 'relative'
      ? { x: previous.x + level.x, y: previous.y + level.y }
      : { x: level.x, y: level.y }
    previous = position
    return {
      id: getCareerLevelIdentity(index, source, repeatIndex, isInfiniteRepeat, level),
      infiniteRepeat: isInfiniteRepeat ? { isTail: isInfiniteTail, repeatIndex, sourceIndex } : undefined,
      level,
      ...position,
    }
  })
}

/** Returns the map index of the current playable Career level. */
export function getCurrentCareerLevelIndexFromPositions(progression: readonly { seed: string }[], positions: readonly CareerLevelPosition[]): number {
  let priorLevelHasProgress = true
  let currentLevelIndex = 0
  for (const [index, position] of positions.entries()) {
    const { level } = position
    if (!level.data) continue
    if (!priorLevelHasProgress) break
    currentLevelIndex = index
    priorLevelHasProgress = progression.some((levelProgression) => levelProgression.seed === position.id)
  }
  return currentLevelIndex
}

/** Returns the map index of the current playable Career level. */
export function getCurrentCareerLevelIndex(progression: readonly { seed: string }[], levels: readonly CareerLevel[] = careerLevels, generation: CareerLevelGeneration = EMPTY_CAREER_LEVEL_GENERATION): number {
  return getCurrentCareerLevelIndexFromPositions(progression, resolveCareerLevelPositions(levels, generation))
}

/** Stable identity derived from a generated virtual level's one-based Career position. */
export function getCareerLevelId(index: number) {
  return `level-${index + 1}`
}

export function isClassicGameDefinitionCareerData(data: CareerLevelData | CareerLevelBuilder): data is ClassicGameDefinition {
  return typeof data !== 'function' && !isCareerLevelDefinitionList(data) && 'pieces' in data
}

/** Returns the board played by default when an authored Career entry has alternatives. */
export function getDefaultCareerLevelData(data: CareerLevelData): ClassicGameDefinition | GameModeConfig {
  if (!isCareerLevelDefinitionList(data)) return data
  const defaultDefinition = data[0]
  if (!defaultDefinition) throw new Error('Career level definition arrays must contain a default board.')
  return defaultDefinition
}

/** Returns a requested authored board alternative, or null when the index cannot be used. */
export function getCareerLevelDataAtIndex(data: CareerLevelData, index: number): ClassicGameDefinition | null {
  if (!isCareerLevelDefinitionList(data) || !Number.isSafeInteger(index) || index < 0) return null
  return data[index] ?? null
}

/** Keeps the primary authored board's legacy progress while assigning virtual levels a positional ID. */
function getCareerLevelIdentity(index: number, sourceLevel: CareerLevel, repeatIndex: number, isInfiniteRepeat: boolean, resolvedLevel: ResolvedCareerLevelConfiguration) {
  const data = resolvedLevel.data
  if (!isInfiniteRepeat && repeatIndex === 0 && !isCareerLevelBuilder(sourceLevel.data) && data) {
    const defaultData = getDefaultCareerLevelData(data)
    if (isClassicGameDefinitionCareerData(defaultData)) return defaultData.seed
  }
  return getCareerLevelId(index)
}

function resolveCareerLevel(entry: ResolvedCareerLevelEntry, index: number): ResolvedCareerLevel {
  const { isInfiniteRepeat, isInfiniteTail, level, repeatIndex, source, sourceIndex } = entry
  return {
    ...(level as PlayableCareerLevel),
    id: getCareerLevelIdentity(index, source, repeatIndex, isInfiniteRepeat, level),
    index,
    infiniteRepeat: isInfiniteRepeat ? { isTail: isInfiniteTail, repeatIndex, sourceIndex } : undefined,
    number: index + 1,
  }
}

export function getCareerLevel(id: string, generation: CareerLevelGeneration = EMPTY_CAREER_LEVEL_GENERATION): ResolvedCareerLevel | null {
  const levels = resolveCareerLevelEntries(careerLevels, generation)
  const index = levels.findIndex((entry, levelIndex) => entry.level.data !== undefined && getCareerLevelIdentity(levelIndex, entry.source, entry.repeatIndex, entry.isInfiniteRepeat, entry.level) === id)
  const level = levels[index]
  return level?.level.data ? resolveCareerLevel(level, index) : null
}

export function getNextCareerLevel(level: ResolvedCareerLevel, generation: CareerLevelGeneration = EMPTY_CAREER_LEVEL_GENERATION): ResolvedCareerLevel | null {
  const levels = resolveCareerLevelEntries(careerLevels, generation)
  for (let index = level.index + 1; index < levels.length; index += 1) {
    const next = levels[index]
    if (next?.level.data) return resolveCareerLevel(next, index)
  }
  return null
}

/** Extends an infinite section only when its latest generated level is completed. */
export function extendCareerLevelGeneration(generation: CareerLevelGeneration, infiniteRepeat: NonNullable<ResolvedCareerLevel['infiniteRepeat']>): CareerLevelGeneration {
  if (!infiniteRepeat.isTail) return generation
  const sourceKey = String(infiniteRepeat.sourceIndex)
  const currentCount = getInfiniteRepeatCount(generation, infiniteRepeat.sourceIndex)
  if (infiniteRepeat.repeatIndex !== currentCount - 1) return generation
  return {
    infiniteRepeats: {
      ...generation.infiniteRepeats,
      [sourceKey]: currentCount + 1,
    },
  }
}

/** Storage identity for the board and attempt state of a Career level. */
export function getCareerGameId(level: Pick<ResolvedCareerLevel, 'id'>) {
  return `career:${level.id}`
}

/** Finds the backing Classic mode for generated Career configurations. */
export function getCareerLevelGameMode(level: ResolvedCareerLevel, dataIndex?: number): ClassicGameMode {
  const data = dataIndex === undefined
    ? getDefaultCareerLevelData(level.data)
    : getCareerLevelDataAtIndex(level.data, dataIndex) ?? getDefaultCareerLevelData(level.data)
  if (isClassicGameDefinitionCareerData(data)) return data.gameMode
  return GAME_MODES.find((mode) => GAME_CONFIGS[mode] === data || GAME_CONFIGS[mode].title === data.title) ?? 'c001'
}

export function getCareerLevelPath(level: Pick<ResolvedCareerLevel, 'id'>) {
  return `/play?${new URLSearchParams({ career: level.id }).toString()}`
}
